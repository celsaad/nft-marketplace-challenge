// Reads the Lighthouse CI runs in docs/lighthouse/<profile>/ and writes docs/lighthouse/summary.md:
// the MEDIAN of each category and of LCP/CLS/TBT over the 3 runs, per page and profile, plus the
// tool versions and environment (spec §Performance).
import { readFileSync, writeFileSync } from 'node:fs'
import { arch, cpus, platform, release, totalmem } from 'node:os'
import { join } from 'node:path'

const ROOT = 'docs/lighthouse'
const PROFILES = ['mobile', 'desktop']
const CATEGORIES = ['performance', 'accessibility', 'best-practices', 'seo']
const TARGETS = { performance: 90, accessibility: 95, 'best-practices': 95, seo: 90 }

const median = (values) => {
  const sorted = [...values].sort((a, b) => a - b)
  const mid = Math.floor(sorted.length / 2)
  return sorted.length % 2 ? sorted[mid] : (sorted[mid - 1] + sorted[mid]) / 2
}
const pageName = (url) => (new URL(url).pathname === '/' ? 'Home' : 'NFT detail')

let lighthouseVersion = 'unknown'
let chromeVersion = 'unknown'
const rows = []

for (const profile of PROFILES) {
  const manifest = JSON.parse(readFileSync(join(ROOT, profile, 'manifest.json'), 'utf8'))
  const byPage = new Map()
  for (const run of manifest) {
    const report = JSON.parse(readFileSync(run.jsonPath, 'utf8'))
    lighthouseVersion = report.lighthouseVersion
    chromeVersion = report.environment?.hostUserAgent?.match(/Chrome\/[\d.]+/)?.[0] ?? chromeVersion
    const key = pageName(run.url)
    const list = byPage.get(key) ?? []
    list.push({
      scores: Object.fromEntries(CATEGORIES.map((c) => [c, Math.round(report.categories[c].score * 100)])),
      lcp: report.audits['largest-contentful-paint'].numericValue,
      cls: report.audits['cumulative-layout-shift'].numericValue,
      tbt: report.audits['total-blocking-time'].numericValue,
      html: run.htmlPath,
    })
    byPage.set(key, list)
  }
  for (const [page, runs] of byPage) {
    rows.push({
      profile,
      page,
      runs: runs.length,
      scores: Object.fromEntries(CATEGORIES.map((c) => [c, median(runs.map((r) => r.scores[c]))])),
      lcp: median(runs.map((r) => r.lcp)),
      cls: median(runs.map((r) => r.cls)),
      tbt: median(runs.map((r) => r.tbt)),
      report: runs[0].html,
    })
  }
}

const mark = (category, value) => (value >= TARGETS[category] ? `${value}` : `**${value}** ⚠️`)
const lines = [
  '# Lighthouse results',
  '',
  `Median of ${rows[0]?.runs ?? 3} runs per page and profile, generated by \`scripts/lighthouse-summary.mjs\` from the`,
  'reports in this folder. Targets: Performance ≥ 90, Accessibility ≥ 95, Best Practices ≥ 95, SEO ≥ 90 (⚠️ = below).',
  '',
  '| Profile | Page | Performance | Accessibility | Best Practices | SEO | LCP | CLS | TBT |',
  '|---|---|---|---|---|---|---|---|---|',
  ...rows.map(
    (r) =>
      `| ${r.profile} | ${r.page} | ${CATEGORIES.map((c) => mark(c, r.scores[c])).join(' | ')} | ${(r.lcp / 1000).toFixed(2)} s | ${r.cls.toFixed(3)} | ${Math.round(r.tbt)} ms |`,
  ),
  '',
  '## Environment',
  '',
  `- Lighthouse ${lighthouseVersion}, ${chromeVersion}, via \`@lhci/cli\` (configs in \`lighthouse/\`)`,
  `- ${platform()} ${release()} (${arch()}), ${cpus()[0]?.model ?? 'unknown CPU'}, ${Math.round(totalmem() / 2 ** 30)} GB RAM`,
  `- Node ${process.version}; optimized build served by \`vite preview\`; default mock Scenario`,
  `- Generated ${new Date().toISOString()}`,
  '',
]
writeFileSync(join(ROOT, 'summary.md'), lines.join('\n'))
console.log(lines.join('\n'))
